/**
 * Helper to get the active daily alignment for a given rank and date
 */
export function getDailyOriForRank(rank: DivinerRank, dateStr?: string): DailyOriAlignment {
  // Normalize rank
  const isOluwo = rank.includes("Olúwo");
  const isBabalawo = rank.includes("Babalawo");
  const isAwoye = rank.includes("Awoyẹ");

  let filtered = DAILY_ORI_ALIGNMENTS.filter((item) => {
    if (isOluwo) return item.rank.includes("Olúwo");
    if (isBabalawo) return item.rank.includes("Babalawo");
    if (isAwoye) return item.rank.includes("Awoyẹ");
    return item.rank.includes("Akẹ́kọ̀ọ́");
  });

  if (filtered.length === 0) {
    filtered = DAILY_ORI_ALIGNMENTS;
  }

  // Use day of year or day number to rotate
  const today = dateStr ? new Date(dateStr) : new Date();
  const dayOfYear = Math.floor(
    (today.getTime() - new Date(today.getFullYear(), 0, 0).getTime()) / (1000 * 60 * 60 * 24)
  );

  const selectedIndex = Math.abs(dayOfYear) % filtered.length;
  return filtered[selectedIndex];
}

/**
 * Format a modern date into an authentic Yoruba seasonal calendar day representation
 */
export function getYorubaDayName(date: Date = new Date()): { yorubaName: string; meaning: string } {
  const days = [
    { yorubaName: "Ọjọ́ Àìkú", meaning: "Day of Immortality & Longevity (Sunday)" },
    { yorubaName: "Ọjọ́ Ajé", meaning: "Day of Prosperity & Commerce (Monday)" },
    { yorubaName: "Ọjọ́ Ìṣẹ́gun", meaning: "Day of Victory & Overcoming Obstacles (Tuesday)" },
    { yorubaName: "Ọjọ́ Rú", meaning: "Day of Sacred Calculation & Balance (Wednesday)" },
    { yorubaName: "Ọjọ́ Bọ̀", meaning: "Day of Ancient Reverence & Lineage (Thursday)" },
    { yorubaName: "Ọjọ́ Ẹtì", meaning: "Day of Receptivity & Community (Friday)" },
    { yorubaName: "Ọjọ́ Àbámẹ́ta", meaning: "Day of Triple Resolutions & Ọ̀rúnmìlà (Saturday)" },
  ];
  return days[date.getDay()];
}
